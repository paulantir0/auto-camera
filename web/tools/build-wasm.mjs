#!/usr/bin/env node
// Assemble src/pipeline/hamming.wat into src/pipeline/hamming-wasm.ts (the
// module's bytes as base64, so workers and tests need no extra file).
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import initWabt from 'wabt';

const root = fileURLToPath(new URL('..', import.meta.url));
const wabt = await initWabt();
const source = await readFile(`${root}src/pipeline/hamming.wat`, 'utf8');
const module = wabt.parseWat('hamming.wat', source, { simd: true });
module.validate();
const { buffer } = module.toBinary({});
const base64 = Buffer.from(buffer).toString('base64');
await writeFile(`${root}src/pipeline/hamming-wasm.ts`,
  `// Generated by tools/build-wasm.mjs from hamming.wat; do not edit.\nexport const HAMMING_WASM = '${base64}';\n`);
console.log(`hamming.wasm: ${buffer.length} bytes`);
