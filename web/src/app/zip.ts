// A ZIP archive of the pictures, stored without compression (JPEGs do not
// shrink). It is assembled as a Blob made of the pictures' own Blobs and
// small headers, so building it copies nothing: the browser streams the parts
// when the file is saved. Pictures kept on disk (origin private file system)
// stay on disk throughout.

export interface ZipEntry { name: string; data: Blob; size: number; crc: number }

const encoder = new TextEncoder();

function dosDateTime(d: Date): [number, number] {
  const time = (d.getHours() << 11) | (d.getMinutes() << 5) | Math.floor(d.getSeconds() / 2);
  const date = ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate();
  return [time, date];
}

export function buildZip(entries: ZipEntry[], when = new Date()): Blob {
  const [time, date] = dosDateTime(when);
  const parts: BlobPart[] = [];
  const central: Uint8Array<ArrayBuffer>[] = [];
  let offset = 0;
  for (const e of entries) {
    const name = encoder.encode(e.name);
    const local = new Uint8Array(30 + name.length);
    const v = new DataView(local.buffer);
    v.setUint32(0, 0x04034b50, true);
    v.setUint16(4, 20, true); // version needed
    v.setUint16(6, 0x0800, true); // UTF-8 names
    v.setUint16(8, 0, true); // stored
    v.setUint16(10, time, true);
    v.setUint16(12, date, true);
    v.setUint32(14, e.crc, true);
    v.setUint32(18, e.size, true);
    v.setUint32(22, e.size, true);
    v.setUint16(26, name.length, true);
    v.setUint16(28, 0, true);
    local.set(name, 30);
    parts.push(local, e.data);
    const c = new Uint8Array(46 + name.length);
    const cv = new DataView(c.buffer);
    cv.setUint32(0, 0x02014b50, true);
    cv.setUint16(4, 20, true);
    cv.setUint16(6, 20, true);
    cv.setUint16(8, 0x0800, true);
    cv.setUint16(10, 0, true);
    cv.setUint16(12, time, true);
    cv.setUint16(14, date, true);
    cv.setUint32(16, e.crc, true);
    cv.setUint32(20, e.size, true);
    cv.setUint32(24, e.size, true);
    cv.setUint16(28, name.length, true);
    cv.setUint32(42, offset, true);
    c.set(name, 46);
    central.push(c);
    offset += local.length + e.size;
    if (offset > 0xffffffff) throw new Error('The pictures add up to more than 4 GB, too much for one ZIP file.');
  }
  let centralSize = 0;
  for (const c of central) { parts.push(c); centralSize += c.length; }
  const end = new Uint8Array(22);
  const ev = new DataView(end.buffer);
  ev.setUint32(0, 0x06054b50, true);
  ev.setUint16(8, entries.length, true);
  ev.setUint16(10, entries.length, true);
  ev.setUint32(12, centralSize, true);
  ev.setUint32(16, offset, true);
  parts.push(end);
  return new Blob(parts, { type: 'application/zip' });
}
